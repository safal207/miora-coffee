#!/usr/bin/env python3
"""Generate the compact browser photo index from the asset manifest."""
import json
from pathlib import Path
ROOT=Path(__file__).resolve().parents[1]
m=json.loads((ROOT/'docs/photo-refresh-2026-11-06.json').read_text())
mapping={id:canonical for canonical,p in m['photos'].items() for id in p['productIds']}
placeholders=['431314','431294','430199','430227','430203','431747','431748','431749']
text='// Generated by scripts/build-photos.py.\nexport const photoSources = Object.freeze('+json.dumps(mapping,sort_keys=True,separators=(',',':'))+');\n'
text+='export const photoPlaceholders = Object.freeze('+json.dumps(placeholders,separators=(',',':'))+');\n'
(ROOT/'dist/photo-data.js').write_text(text)
print(f'Indexed {len(mapping)} product photos.')
