#!/usr/bin/env python3
"""Generate the compact browser photo index from the asset manifest."""
import json
from pathlib import Path
ROOT=Path(__file__).resolve().parents[1]
m=json.loads((ROOT/'docs/photo-refresh-2026-11-06.json').read_text())
mapping={id:canonical for canonical,p in m['photos'].items() for id in p['productIds']}
placeholders=['431314','431294','430199','430227','430203','431747','431748','431749']
text='// Generated by scripts/build-photos.py.\nexport const photoSources = Object.freeze('+json.dumps(mapping,sort_keys=True,separators=(',',':'))+');\n'
text+='export const photoPlaceholders = Object.freeze('+json.dumps(placeholders,separators=(',',':'))+');\n'
(ROOT/'dist/photo-data.js').write_text(text)
print(f'Indexed {len(mapping)} product photos.')

# Build the original-photo index from the committed provenance manifest.
original=json.loads((ROOT/'docs/original-photo-refresh-2026-11-12.json').read_text(encoding='utf8'))
data={id:{'width':p['sourceDimensions'][0],'height':p['sourceDimensions'][1],'assets':{width:{'src':a['path'],'width':a['dimensions'][0]} for width,a in p['assets'].items()}} for id,p in original['photos'].items()}
(ROOT/'dist/original-photo-data.js').write_text('// Original menu photography, encoded without upscaling. See docs/original-photo-refresh-2026-11-12.json.\nexport const originalPhotos = Object.freeze('+json.dumps(data,separators=(',',':'))+');\n',encoding='utf8')

# Generated examples remain separate from original-photo provenance.
generated=json.loads((ROOT/'docs/generated-menu-illustrations-2026-11-12.json').read_text(encoding='utf8'))
index={id:{'width':p['sourceDimensions'][0],'height':p['sourceDimensions'][1],'assets':{w:{'src':a['path'],'width':a['dimensions'][0]} for w,a in p['assets'].items()}} for id,p in generated['photos'].items()}
(ROOT/'dist/generated-photo-data.js').write_text('// Generated by scripts/build-photos.py; AI serving illustrations, not restaurant photographs.\nexport const generatedPhotos = Object.freeze('+json.dumps(index,separators=(',',':'))+');\n',encoding='utf8')
